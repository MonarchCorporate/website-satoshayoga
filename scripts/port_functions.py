#!/usr/bin/env python3
"""Mechanically port the Supabase (Deno) edge functions to Node modules.

  python3 -I scripts/port_functions.py lovable-original/supabase/functions server/functions

Transformations (everything else stays byte-identical):
  * supabase-js imports      -> ../../src/supabase-server (self-hosted engine)
  * esm.sh / npm: specifiers  -> plain npm package names
  * denomailer SMTPClient     -> nodemailer based compat layer
  * Deno.env.get(...)         -> __env(...)
  * Deno.serve(handler)       -> export default (handler)
"""
import os
import re
import sys

src_root, dst_root = sys.argv[1], sys.argv[2]

IMPORT_MAP = {
    "https://esm.sh/@supabase/supabase-js@2.45.0": "../../src/supabase-server",
    "npm:@supabase/supabase-js@2.45.0": "../../src/supabase-server",
    "https://esm.sh/pdf-lib@1.17.1": "pdf-lib",
    "npm:nodemailer@6.9.14": "nodemailer",
    "https://deno.land/x/denomailer@1.6.0/mod.ts": "../../src/denomailer-compat",
}

names = []
for entry in sorted(os.listdir(src_root)):
    sdir = os.path.join(src_root, entry)
    if not os.path.isdir(sdir):
        continue
    ddir = os.path.join(dst_root, entry)
    os.makedirs(ddir, exist_ok=True)
    for fn in os.listdir(sdir):
        if not fn.endswith(".ts"):
            continue
        code = open(os.path.join(sdir, fn), encoding="utf-8").read()
        for k, v in IMPORT_MAP.items():
            code = code.replace(f'"{k}"', f'"{v}"')
        unknown = re.findall(r'from "((?:https?|npm|jsr):[^"]+)"', code)
        if unknown:
            raise SystemExit(f"unmapped import in {entry}/{fn}: {unknown}")
        uses_env = "Deno.env.get(" in code
        code = code.replace("Deno.env.get(", "__env(")
        if "Deno.serve(" in code:
            code = code.replace("Deno.serve(", "export default (", 1)
            names.append(entry)
        if re.search(r"\bDeno\.", code):
            raise SystemExit(f"remaining Deno API in {entry}/{fn}: {re.findall(r'Deno\\.[a-zA-Z.]+', code)}")
        header = "// Ported from supabase/functions (Deno) by scripts/port_functions.py\n"
        if uses_env:
            header += 'import { __env } from "../../src/fn-env";\n'
        open(os.path.join(ddir, fn), "w", encoding="utf-8").write(header + code)

# Registry module importing every function handler
lines = ["// Generated by scripts/port_functions.py", "export const handlers: Record<string, (req: Request) => Promise<Response> | Response> = {"]
imports = []
for i, n in enumerate(names):
    imports.append(f'import h{i} from "./{n}/index";')
    lines.append(f'  "{n}": h{i} as any,')
lines.append("};")
open(os.path.join(dst_root, "index.ts"), "w").write("\n".join(imports + lines) + "\n")
print(f"ported {len(names)} functions")
